export function detectLang(locale: string): Lang {
  const l = locale.toLowerCase();
  if (l.startsWith("zh")) return /hant|tw|hk|mo/.test(l) ? "zh-Hant" : "zh-Hans";
  for (const code of ["ko", "tr", "es"] as const) if (l.startsWith(code)) return code;
  return "en";
}

let lang: Lang = "en";
export const setLang = (next: Lang) => { lang = next; };

export function t(key: Key, vars: Record<string, string | number> = {}): string {
  return STRINGS[lang][key].replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? ""));
}
